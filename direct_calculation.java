package daksh;

public class direct_calculation {
    static void main(String[] args) {
        int a = 50;
        int b = 60;

        int sum = a+b;
        int mul = a*b;
        float div = (float) a/b;
        int sub = a-b;
        System.out.println("The given answer is "+ sum);
        System.out.println("The given answer is "+ mul);
        System.out.println("The given answer is "+ div);
        System.out.println("The given answer is "+ sub);
    }
}
